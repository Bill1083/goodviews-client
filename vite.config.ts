import { defineConfig, loadEnv, type Plugin } from 'vite'
import react from '@vitejs/plugin-react'
import { BRAND, BRAND_HAS_PLACEHOLDERS } from './src/config/brand'
import { PREBUILT_PATHS, PRIVATE_PATH_PREFIXES, PUBLIC_PAGES, SITEMAP_PATHS, documentTitle, type PublicPath } from './src/config/seo'

function escapeHtml(value: string): string {
  return value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
}

function absolute(path: string): string {
  return `${BRAND.siteUrl}${path}`
}

function canonicalFor(path: PublicPath): string {
  return path === '/' ? absolute('/') : absolute(path)
}

/** The site-wide structured data: who we are and what the site is. */
function jsonLd(): string {
  const data = [
    {
      '@context': 'https://schema.org',
      '@type': 'WebSite',
      name: BRAND.name,
      url: absolute('/'),
      description: BRAND.description,
    },
    {
      '@context': 'https://schema.org',
      '@type': 'Organization',
      name: BRAND.name,
      url: absolute('/'),
      logo: absolute('/favicon.svg'),
    },
  ]
  // "<" escaped so the JSON can never close its own <script> tag.
  return JSON.stringify(data).replace(/</g, '\\u003c')
}

function ogImageTags(): string {
  if (!BRAND.ogImage) return '<meta name="twitter:card" content="summary" />'
  const url = escapeHtml(absolute(BRAND.ogImage))
  return [
    `<meta property="og:image" content="${url}" />`,
    '<meta property="og:image:width" content="1200" />',
    '<meta property="og:image:height" content="630" />',
    '<meta name="twitter:card" content="summary_large_image" />',
    `<meta name="twitter:image" content="${url}" />`,
  ].join('\n    ')
}

/** Fills the %BRAND_*% tokens in index.html (Vite fills %VITE_*% itself). */
function fillTokens(html: string): string {
  const home = PUBLIC_PAGES['/']
  const tokens: Record<string, string> = {
    BRAND_NAME: escapeHtml(BRAND.name),
    BRAND_TAGLINE: escapeHtml(BRAND.tagline),
    BRAND_TITLE: escapeHtml(documentTitle(home.title)),
    BRAND_DESCRIPTION: escapeHtml(home.description),
    BRAND_CANONICAL: escapeHtml(canonicalFor('/')),
    BRAND_LOCALE: escapeHtml(BRAND.locale),
    BRAND_THEME_COLOR: escapeHtml(BRAND.themeColor),
    BRAND_JSON_LD: jsonLd(),
    BRAND_OG_IMAGE_TAGS: ogImageTags(),
  }
  return html.replace(/%(BRAND_[A-Z_]+)%/g, (match, key: string) => tokens[key] ?? match)
}

/** The built shell, re-titled for one public page. */
function withPageMeta(html: string, path: PublicPath): string {
  const page = PUBLIC_PAGES[path]
  const title = escapeHtml(documentTitle(page.title))
  const description = escapeHtml(page.description)
  const url = escapeHtml(canonicalFor(path))
  const setContent = (source: string, attr: string, value: string) =>
    source.replace(new RegExp(`(<meta ${attr} content=")[^"]*(")`), `$1${value}$2`)

  let out = html.replace(/<title>[^<]*<\/title>/, `<title>${title}</title>`)
  out = out.replace(/(<link rel="canonical" href=")[^"]*(")/, `$1${url}$2`)
  out = setContent(out, 'name="description"', description)
  out = setContent(out, 'property="og:title"', title)
  out = setContent(out, 'property="og:description"', description)
  out = setContent(out, 'property="og:url"', url)
  out = setContent(out, 'name="twitter:title"', title)
  out = setContent(out, 'name="twitter:description"', description)
  return out
}

function robotsTxt(apiBase: string): string {
  const lines = ['User-agent: *', 'Allow: /', ...PRIVATE_PATH_PREFIXES.map((p) => `Disallow: ${p}`), '']
  lines.push(`Sitemap: ${absolute('/sitemap.xml')}`)
  // The film pages' sitemap is generated by the API. A sitemap on another
  // host is valid when this host's robots.txt points at it. Skipped for
  // local builds, whose API is localhost.
  if (apiBase && !/localhost|127\.0\.0\.1/.test(apiBase)) {
    lines.push(`Sitemap: ${apiBase.replace(/\/$/, '')}/api/sitemap/films.xml`)
  }
  return `${lines.join('\n')}\n`
}

function sitemapXml(): string {
  const today = new Date().toISOString().slice(0, 10)
  const urls = SITEMAP_PATHS.map(
    (path) => `  <url>\n    <loc>${escapeHtml(canonicalFor(path))}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`,
  )
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`
}

function webManifest(): string {
  return `${JSON.stringify(
    {
      name: BRAND.name,
      short_name: BRAND.name,
      description: BRAND.description,
      start_url: '/',
      display: 'standalone',
      background_color: BRAND.backgroundColor,
      theme_color: BRAND.themeColor,
      icons: [{ src: '/favicon.svg', sizes: 'any', type: 'image/svg+xml' }],
    },
    null,
    2,
  )}\n`
}

/** RFC 9116: where to report a security problem. */
function securityTxt(): string {
  const expires = new Date()
  expires.setFullYear(expires.getFullYear() + 1)
  const contact = BRAND.contactEmail.includes('@') ? `mailto:${BRAND.contactEmail}` : absolute('/privacy#contact')
  return [
    `Contact: ${contact}`,
    `Expires: ${expires.toISOString()}`,
    'Preferred-Languages: en',
    `Canonical: ${absolute('/.well-known/security.txt')}`,
    `Policy: ${absolute('/privacy')}`,
    '',
  ].join('\n')
}

/**
 * Everything brand- and SEO-shaped that has to exist as a file rather than be
 * set from React: the filled-in index.html, robots.txt, sitemap.xml, the web
 * manifest, security.txt, and a pre-titled HTML copy of each public page.
 */
function brandPlugin(apiBase: string): Plugin {
  return {
    name: 'brand',
    transformIndexHtml: {
      order: 'pre',
      handler: fillTokens,
    },
    generateBundle: {
      order: 'post',
      handler(_options, bundle) {
        const files: Record<string, string> = {
          'robots.txt': robotsTxt(apiBase),
          'sitemap.xml': sitemapXml(),
          'site.webmanifest': webManifest(),
          '.well-known/security.txt': securityTxt(),
        }
        const shell = bundle['index.html']
        if (shell && shell.type === 'asset') {
          for (const path of PREBUILT_PATHS) {
            files[`${path.slice(1)}/index.html`] = withPageMeta(String(shell.source), path)
          }
        } else {
          this.warn('index.html missing from the bundle — per-page HTML not generated')
        }
        for (const [fileName, source] of Object.entries(files)) {
          this.emitFile({ type: 'asset', fileName, source })
        }
        if (BRAND_HAS_PLACEHOLDERS) {
          this.warn('src/config/brand.ts still has TODO placeholders (operator, contact email, governing law). Fill them in before launch.')
        }
      },
    },
  }
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, '.', 'VITE_')
  return {
    plugins: [react(), brandPlugin(env.VITE_API_BASE_URL ?? '')],
    build: {
      rollupOptions: {
        output: {
          // Libraries change far less often than the app: in their own
          // chunks they stay cached across deploys.
          manualChunks(id: string) {
            if (id.includes('/node_modules/@supabase/')) return 'supabase'
            if (/\/node_modules\/(react|react-dom|scheduler|react-router|react-router-dom|@remix-run)\//.test(id)) return 'react'
            if (/\/node_modules\/(@tanstack|axios|zustand)\//.test(id)) return 'vendor'
            return undefined
          },
        },
      },
    },
    server: {
      port: 5173,
    },
  }
})
